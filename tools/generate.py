"""Generate firmware tables, wiring docs, and the wiring diagram from diagnostics/model.py.

The key map is only generated after checking the saved hardware measurements.
Run with --check to fail if any generated file is out of date.
"""
import json
import re
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from diagnostics.model import (EXPECTED, ROWS, COLS, WIRING, WIRING_ID, ORDER, FPC_WIRES, RIBBON_WIRES,
                               COLORS, BUTTONS, LEDS, LED_RESISTOR, PADS, TEENSY_LEFT, TEENSY_RIGHT)

CODES={chr(ord('A')+i):4+i for i in range(26)}
CODES.update({str(i):29+i for i in range(1,10)})
CODES['0']=39
CODES.update({f'F{i}':57+i for i in range(1,13)})
CODES.update({'Enter':40,'Esc':41,'Backspace':42,'Tab':43,'Space':44,'-':45,'=':46,
              '[':47,']':48,'\\':49,';':51,"'":52,'`':53,',':54,'.':55,'/':56,
              'Caps Lock':57,'PrtSc':70,'Insert':73,'Home':74,'PgUp':75,'Delete':76,
              'End':77,'PgDn':78,'Right':79,'Left':80,'Down':81,'Up':82,
              'LCtrl':224,'LShift':225,'LAlt':226,'Super':227,'RCtrl':228,
              'RShift':229,'RAlt':230,'Fn':255})
HEX={'brown':'#795548','red':'#d32f2f','orange':'#f57c00','yellow':'#ffeb3b','green':'#2e7d32',
     'blue':'#1565c0','purple':'#7b1fa2','gray':'#757575','white':'#ffffff','black':'#111111'}
ROW_NAMES={pin:f'R{i}' for i,pin in enumerate(ROWS)}
COL_NAMES={pin:f'C{i}' for i,pin in enumerate(COLS)}
LED_PIN_NAMES={'Caps Lock':'CAPS','Mic mute':'MIC','Speaker mute':'SPEAKER','Fn Lock':'FN_LOCK'}


def color(wire):
    if wire in RIBBON_WIRES: return RIBBON_WIRES[wire][1]
    return COLORS[int(wire[1:])-1]


def fpc_role(fpc):
    if fpc in ROW_NAMES: return 'Key row '+ROW_NAMES[fpc]
    if fpc in COL_NAMES: return 'Key column '+COL_NAMES[fpc]
    for name,(line,common) in BUTTONS.items():
        if fpc==line: return name+' mouse button'
        if fpc==common: return 'Mouse button common'
    for name,contact in LEDS.items():
        if fpc==contact: return f'{name} LED − (through {LED_RESISTOR})'
    if fpc==16: return 'Indicator LED common +'
    raise ValueError(f'FPC {fpc} has no role')


def pad(pin): return f'pin {pin}' if isinstance(pin,int) else PADS[pin]


def teensy_pin(fpc): return next(pin for contact,pin in FPC_WIRES.values() if contact==fpc)


def check_report(report):
    if report['metadata']['mode']!='hardware': raise ValueError('Hardware measurements required')
    # FPC pairs are board-independent; the report must cover every matrix contact.
    if not set(map(int,report['wiring']))>={*ROWS,*COLS}: raise ValueError('Wiring mismatch')
    if set(report['keys'])!=set(EXPECTED): raise ValueError('Need all 84 keys')
    for key,pair in EXPECTED.items():
        measurement=report['keys'][key]
        if (measurement['status']!='pass' or measurement['observed']!=[list(pair)]
                or measurement['expected']!=list(pair)):
            raise ValueError('Unverified key: '+key)


def generated(report):
    check_report(report)
    lines=['// Generated by tools/generate.py from docs/verified-report.json.',
           '#include "keymap.h"',
           'const uint8_t row_pins[KB_ROWS]={'+','.join(str(WIRING[p]) for p in ROWS)+'};',
           'const uint8_t col_pins[KB_COLS]={'+','.join(str(WIRING[p]) for p in COLS)+'};',
           'const uint8_t keymap[KB_ROWS][KB_COLS]={']
    for pin,keys in ROWS.items():
        padded=keys+[None]*(len(COLS)-len(keys))
        lines.append('    {'+','.join(str(CODES[k]) if k else '0' for k in padded)+'}, // FPC '+str(pin))
    lines.append('};\n')
    return '\n'.join(lines)


def pins_header():
    tp={signal:pin for signal,_,pin in RIBBON_WIRES.values()}
    lines=['// Generated by tools/generate.py from diagnostics/model.py.',
           '#ifndef T14_PINS_H','#define T14_PINS_H',
           f'#define T14_WIRING_ID "{WIRING_ID}"']
    for name,(line,common) in BUTTONS.items():
        lines.append(f'#define PIN_BUTTON_{name.upper()} {teensy_pin(line)}')
    lines.append(f'#define PIN_BUTTON_COMMON {teensy_pin(next(iter(BUTTONS.values()))[1])}')
    for name,contact in LEDS.items():
        lines.append(f'#define PIN_LED_{LED_PIN_NAMES[name]} {teensy_pin(contact)}')
    lines+=[f'#define PIN_TP_CLK {tp["TrackPoint CLK"]}',f'#define PIN_TP_DATA {tp["TrackPoint DATA"]}',
            f'#define PIN_TP_RST {tp["TrackPoint RST"]}',f'#define PIN_BACKLIGHT {tp["Backlight gate"]}',
            f'#define SCAN_COUNT {len(WIRING)}',
            '#define SCAN_FPC {'+','.join(map(str,WIRING))+'}',
            '#define SCAN_PINS {'+','.join(map(str,WIRING.values()))+'}','#endif','']
    return '\n'.join(lines)


def verified_keymap(report):
    check_report(report)
    lines=['# Verified T14 key map','',
           '84/84 keys passed in the saved hardware test ([verified-report.json](verified-report.json)). '
           'That test ran on the earlier Pico build; FPC contact pairs belong to the keyboard, so they carry '
           'over unchanged. Teensy pins come from the current wiring. Fn is handled locally; all other values '
           'are USB HID Keyboard/Keypad usage IDs.','',
           '| Key | FPC contacts | Teensy pins | USB usage |','| :--- | :--- | :--- | :--- |']
    for key in ORDER:
        a,b=EXPECTED[key]
        label=key.replace('\\','&#92;').replace('`','&#96;').replace('|','&#124;')
        usage='Fn (local)' if key=='Fn' else f'0x{CODES[key]:02X}'
        lines.append(f'| {label} | {a} + {b} | {WIRING[a]} + {WIRING[b]} | {usage} |')
    return '\n'.join(lines)+'\n'


def badge(name): return f'![{name.title()}](docs/wire-colors/{name}.svg)'


def readme_tables():
    lines=['| Wire | Color | FPC | Teensy | Function |','| :--- | :--- | ---: | :--- | :--- |']
    for wire,(fpc,pin) in FPC_WIRES.items():
        lines.append(f'| {wire} | {badge(color(wire))} | {fpc} | {pad(pin)} | {fpc_role(fpc)} |')
    lines+=['','| Wire | Color | Ribbon signal | Teensy | Notes |','| :--- | :--- | :--- | :--- | :--- |']
    notes={'TrackPoint Vcc':'3.3 V only','TrackPoint GND':'Black is ground here',
           'Backlight V+':'5 V from USB','Backlight gate':'PWM brightness'}
    for wire,(signal,name,pin) in RIBBON_WIRES.items():
        lines.append(f'| {wire} | {badge(name)} | {signal} | {pad(pin)} | {notes.get(signal,"")} |')
    return '\n'.join(lines)


def wiring_svg():
    """Top view of a Teensy 4.1 at roughly true proportions, with each wire's far end labeled."""
    pitch,top,width=22,60,860
    cx=width//2
    left,right=cx-66,cx+66            # pin rows are 0.6 in apart
    bottom=top+23*pitch
    height=bottom+70
    short={fpc:name.lower()+' button' for name,(fpc,_) in BUTTONS.items()}
    short.update({fpc:name+' LED' for name,fpc in LEDS.items()})
    short.update({9:'button common',16:'LED +'})
    attached={}
    for wire,(fpc,pin) in FPC_WIRES.items():
        attached[pin]=(wire,f'FPC {fpc}'+(f' {short[fpc]}' if fpc in short else ''),color(wire),fpc in LEDS.values())
    for wire,(signal,name,pin) in RIBBON_WIRES.items(): attached[pin]=(wire,signal,name,False)
    out=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
         'font-family="Helvetica, Arial, sans-serif" font-size="12" role="img" aria-label="Teensy 4.1 wiring for the T14 keyboard">',
         f'<rect width="{width}" height="{height}" fill="#fbfbf8"/>',
         # board, micro-USB socket, i.MX RT chip, SD card socket
         f'<rect x="{left-22}" y="{top-26}" width="{right-left+44}" height="{bottom-top+62}" rx="5" fill="#16613a" stroke="#0e3f26"/>',
         f'<rect x="{cx-18}" y="{top-36}" width="36" height="24" rx="2" fill="#c9cccf" stroke="#8a8f94"/>',
         f'<rect x="{cx-28}" y="{top+5*pitch}" width="56" height="56" rx="2" fill="#2b2d30"/>',
         f'<rect x="{cx-32}" y="{bottom-32}" width="64" height="44" rx="2" fill="#b5b8bb" stroke="#8a8f94"/>']
    for side,pads in (('L',TEENSY_LEFT),('R',TEENSY_RIGHT)):
        x=left if side=='L' else right
        for i,pin in enumerate(pads):
            y=top+i*pitch
            label=pin if isinstance(pin,int) else {'GND_L':'G','GND_R':'G','GND':'G','3V3_L':'3V','3V3_R':'3V','VIN':'VIN'}[pin]
            tx,anchor=(x+11,'start') if side=='L' else (x-11,'end')
            out.append(f'<text x="{tx}" y="{y+4}" text-anchor="{anchor}" font-size="10" fill="#e9f3ec">{label}</text>')
            if pin in attached:
                wire,text,name,resistor=attached[pin]
                end=x-150 if side=='L' else x+150
                edge=' stroke="#555" stroke-width="0.6"' if name in ('white','yellow') else ''
                out.append(f'<rect x="{min(x,end)}" y="{y-2}" width="150" height="4" rx="2" fill="{HEX[name]}"{edge}/>')
                if resistor:
                    mid=(x+end)/2
                    out.append(f'<rect x="{mid-13}" y="{y-5}" width="26" height="10" rx="4" fill="#d8c29d" stroke="#9b8462" stroke-width="0.6"/>')
                    for k,band in enumerate(['#e07b00','#e07b00','#7a4a1e','#c9a227']):  # 330 ohm
                        out.append(f'<rect x="{mid-8+k*5+(2 if k==3 else 0)}" y="{y-5}" width="2" height="10" fill="{band}"/>')
                lx,anchor=(end-8,'end') if side=='L' else (end+8,'start')
                out.append(f'<text x="{lx}" y="{y+4}" text-anchor="{anchor}" fill="#2a2a2a">'
                           f'<tspan font-weight="bold">{wire}</tspan>  {text}</text>')
            out.append(f'<circle cx="{x}" cy="{y}" r="6" fill="#c8a24a"/><circle cx="{x}" cy="{y}" r="2.6" fill="#1b1b1b"/>')
    out.append(f'<text x="{cx}" y="{height-22}" text-anchor="middle" font-size="11" fill="#777">'
               f'Top view, USB up. G = ground, 3V = 3.3 V. Bands = {LED_RESISTOR} resistor.</text>')
    out.append('</svg>')
    return '\n'.join(out)+'\n'


def readme(current):
    start,end='<!-- wiring-tables:start -->','<!-- wiring-tables:end -->'
    pattern=re.compile(re.escape(start)+'.*?'+re.escape(end),re.S)
    if not pattern.search(current): raise ValueError('README wiring markers missing')
    return pattern.sub(lambda _:start+'\n'+readme_tables()+'\n'+end,current)


def outputs():
    report=json.loads((ROOT/'docs/verified-report.json').read_text(encoding='utf-8'))
    return {ROOT/'firmware/keymap.c':generated(report),
            ROOT/'firmware/pins.h':pins_header(),
            ROOT/'docs/verified-keymap.md':verified_keymap(report),
            ROOT/'docs/wiring.svg':wiring_svg(),
            ROOT/'README.md':readme((ROOT/'README.md').read_text(encoding='utf-8'))}


if __name__=='__main__':
    stale=[]
    for path,content in outputs().items():
        current=path.read_text(encoding='utf-8') if path.exists() else None
        if current==content: continue
        if '--check' in sys.argv: stale.append(str(path.relative_to(ROOT)))
        else: path.write_text(content,encoding='utf-8')
    if stale: raise SystemExit('Out of date, run python tools/generate.py: '+', '.join(stale))
